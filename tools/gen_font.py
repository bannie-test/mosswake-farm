def main():
    chars = sorted(G)
    widths = {c: max(len(r) for r in G[c]) for c in chars}
    total = sum(w + 1 for w in widths.values())
    img = Image.new("RGBA", (total, H), (0, 0, 0, 0))
    lines = ['info face="Mosswake" size=9 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
             f"common lineHeight=11 base=8 scaleW={total} scaleH={H} pages=1 packed=0",
             'page id=0 file="font_mosswake.png"', f"chars count={len(chars)}"]
    x = 0
    for c in chars:
        rows = G[c]
        for y, row in enumerate(rows):
            for dx, ch in enumerate(row):
                if ch == "#":
                    img.putpixel((x + dx, y), (255, 255, 255, 255))
        w = widths[c]
        lines.append(f"char id={ord(c)} x={x} y=0 width={w} height={H} xoffset=0 yoffset=1 xadvance={w + 1} page=0 chnl=15")
        x += w + 1
    os.makedirs(OUT, exist_ok=True)
    img.save(os.path.join(OUT, "font_mosswake.png"))
    with open(os.path.join(OUT, "font_mosswake.fnt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"font written: {len(chars)} glyphs, atlas {total}x{H}")


if __name__ == "__main__":
    main()
